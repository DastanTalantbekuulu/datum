CREATE OR REPLACE FUNCTION trigger_set_updated()
    RETURNS TRIGGER AS
$$
BEGIN
    NEW.updated_at := now();
RETURN NEW;
END;
$$ LANGUAGE plpgsql;


CREATE TABLE users

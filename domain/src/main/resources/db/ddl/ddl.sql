    deleted_by    BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    deleted_at    TIMESTAMPTZ,

    CONSTRAINT check_relation_self CHECK (person_id <> relative_id),
    UNIQUE (person_id, relative_id, relation_type)
);

